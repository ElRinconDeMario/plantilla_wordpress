console.log('5 === 5            ->', 5 === 5);
console.log('5 === "5"          ->', 5 === "5");
console.log('5 == "5"           ->', 5 == "5");
console.log('0 === false        ->', 0 === false);
console.log('0 == false         ->', 0 == false);
console.log('"" === false       ->', "" === false);
console.log('"" == false        ->', "" == false);
console.log('null === undefined ->', null === undefined);
console.log('null == undefined  ->', null == undefined);